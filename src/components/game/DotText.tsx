export function DotText({
  text,
  className,
  r = 2.05,
  pitch = 5.2,
  dim = false,
  label,
}: {
  text: string;
  className?: string;
  r?: number;
  pitch?: number;
  dim?: boolean;
  label?: string;
}) {
  const chars = [...text.toUpperCase()].map((c) => (c === "X" && !G["X"] ? G["x"]! : G[c] ?? G[" "]!));
  let x = 0;
  const dots: { cx: number; cy: number; on: boolean }[] = [];
  for (const g of chars) {
    const w = g[0]!.length;
    for (let row = 0; row < 7; row++) {
      for (let col = 0; col < w; col++) {
        const on = g[row]![col] === "1";
        if (on || dim) dots.push({ cx: x + col * pitch + r, cy: row * pitch + r, on });
      }
    }
    x += w * pitch + pitch;
  }
  const width = Math.max(x - pitch + r * 2 - (pitch - r * 2), 1);
  const height = 6 * pitch + r * 2;
  return (
    <svg className={className ?? "dot-svg"} viewBox={`0 0 ${width} ${height}`} role="img" aria-label={label ?? text}>
      {dots.map((d, i) => (
        <circle key={i} cx={d.cx} cy={d.cy} r={r} fill="currentColor" fillOpacity={d.on ? 1 : 0.12} />
      ))}
    </svg>
  );
}
